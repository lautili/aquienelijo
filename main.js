createTags();
function createTags(){
    for(let card of CARTAS){
        if(tags.includes(card.tag)){
            continue;
        }
        tags.push(card.tag);
    }
    let div = document.querySelector(".tags");
    for (let tag of tags){
        let id = tag.toLowerCase();
        id = id.replaceAll(" ", "");
        tagIDs.push(id);
        let input = document.createElement("input");
        let label = document.createElement("label");
        console.log(tag);
        console.log(id);
        input.type = "checkbox";
        input.id = id;
        input.name = id;
        input.value = id;
        label.htmlFor = input.id;
        label.textContent = tag;
        input.addEventListener("click", updateBlackTags);
        div.appendChild(input);
        div.appendChild(label);
    }
}
function updateBlackTags(e){
    let id = e.target.id;
    if(blackedIDs.includes(id)){
       let index = blackedIDs.indexOf(id);
       blackedIDs.splice(index, 1);
    }else{
        blackedIDs.push(id);
    }
    createCards();
    let cards2 = document.querySelector("#Cartas2");
    if(cards2.innerHTML != ""){
        createCards2();
    }
}

function checkBlackTags(tag){
    let id = tag.toLowerCase().replaceAll(" ", "");
    return blackedIDs.includes(id);
}

createCards();
function createCards(){
    let board = document.querySelector("#Cartas");
    board.innerHTML = "";

    for (let card of CARTAS){
        if(checkBlackTags(card.tag)){
            continue;
        }
        let div = document.createElement('div');
        let pfp = document.createElement('img');
        let name = document.createElement('h2');
        let {img, nombre} = card;
        pfp.src=img;
        name.textContent=nombre;
        div.classList.add("card_normal");
        div.append(pfp, name);
        div.addEventListener("click", handleClick);
        board.append(div);
    }
}
